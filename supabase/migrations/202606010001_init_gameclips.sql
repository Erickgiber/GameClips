create or replace function public.refresh_profile_counters(target_user_id uuid default null)
returns void
language sql
as $$
	update public.profiles p
	set
		videos_count = (
			select count(*)::int
			from public.videos v
			where v.user_id = p.id
		),
		followers_count = (
			select count(*)::int
			from public.follows f
			where f.following_id = p.id
		),
		following_count = (
			select count(*)::int
			from public.follows f
			where f.follower_id = p.id
		),
		saved_videos_count = (
			select count(*)::int
			from public.saved_videos sv
			where sv.user_id = p.id
		),
		liked_videos_count = (
			select count(*)::int
			from public.video_likes vl
			where vl.user_id = p.id
		),
		likes_count = (
			select count(*)::int
			from public.video_likes vl
			join public.videos v on v.id = vl.video_id
			where v.user_id = p.id
		)
	where target_user_id is null or p.id = target_user_id;
$$;

create or replace function public.get_videos_feed(p_limit integer default 30)
returns table (
	id uuid,
	user_id uuid,
	title text,
	video_url text,
	created_at timestamptz,
	username text,
	avatar_url text
)
language sql
stable
as $$
	select
		v.id,
		v.user_id,
		v.title,
		v.video_url,
		v.created_at,
		p.username,
		p.avatar_url
	from public.videos v
	left join public.profiles p on p.id = v.user_id
	order by v.created_at desc
	limit greatest(coalesce(p_limit, 30), 1);
$$;

grant execute on function public.get_videos_feed(integer) to anon, authenticated;

