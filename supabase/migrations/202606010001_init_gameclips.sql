create or replace function public.update_profile_like_counts()
returns trigger
language plpgsql
as $$
declare
	v_video_owner uuid;
begin
	if tg_op = 'INSERT' then
		select v.user_id into v_video_owner from public.videos v where v.id = new.video_id;

		update public.profiles set liked_videos_count = liked_videos_count + 1 where id = new.user_id;

		if v_video_owner is not null then
			update public.profiles set likes_count = likes_count + 1 where id = v_video_owner;
		end if;

		return new;
	elsif tg_op = 'DELETE' then
		select v.user_id into v_video_owner from public.videos v where v.id = old.video_id;

		update public.profiles
		set liked_videos_count = greatest(liked_videos_count - 1, 0)
		where id = old.user_id;

		if v_video_owner is not null then
			update public.profiles
			set likes_count = greatest(likes_count - 1, 0)
			where id = v_video_owner;
		end if;

		return old;
	end if;

	return null;
end;
$$;

