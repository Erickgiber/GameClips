create or replace function public.update_profile_video_count()
returns trigger
language plpgsql
as $$
begin
	if tg_op = 'INSERT' then
		update public.profiles set videos_count = videos_count + 1 where id = new.user_id;
		return new;
	elsif tg_op = 'DELETE' then
		update public.profiles set videos_count = greatest(videos_count - 1, 0) where id = old.user_id;
		-- Video delete can cascade likes; recompute received likes from remaining videos.
		update public.profiles p
		set likes_count = (
			select count(*)::int
			from public.video_likes vl
			join public.videos v on v.id = vl.video_id
			where v.user_id = old.user_id
		)
		where p.id = old.user_id;
		return old;
	end if;

	return null;
end;
$$;

